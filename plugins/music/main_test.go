package main

import "testing"

func TestExtractSongName(t *testing.T) {
	tests := []struct {
		input    string
		expected string
	}{
		// 误触发日常对话案例（必须返回空，绝不能误触发点歌）
		{"给我看看", ""},
		{"给我看下", ""},
		{"给我发照片", ""},
		{"给我发个红包", ""},
		{"给我倒杯水", ""},
		{"给我等等", ""},
		{"发我看看", ""},
		{"发给我看看", ""},
		{"发我照片", ""},
		{"发我定位", ""},
		{"听听看", ""},
		{"听下这个", ""},
		{"听一下这个", ""},
		{"要听话", ""},
		{"我想听你的声音", ""},
		{"我想听你说话", ""},
		{"我想听故事", ""},
		{"我想听八卦", ""},
		{"我想听语音", ""},
		{"点歌", ""},
		{"我想听歌", ""},
		{"我要听歌", ""},
		{"放首歌", ""},

		// 真实点歌案例（必须准确提取歌名）
		{"点歌 晴天", "晴天"},
		{"点歌晴天", "晴天"},
		{"放歌 稻香", "稻香"},
		{"搜歌 七里香", "七里香"},
		{"音乐 晴天", "晴天"},
		{"music 晴天", "晴天"},
		{"来一首晴天", "晴天"},
		{"来首晴天", "晴天"},
		{"点一首晴天", "晴天"},
		{"放一首晴天", "晴天"},
		{"搜一首晴天", "晴天"},
		{"发一首晴天", "晴天"},
		{"来首歌 晴天", "晴天"},
		{"放首歌 晴天", "晴天"},
		{"点首歌 晴天", "晴天"},
		{"给我来首晴天", "晴天"},
		{"给我放首晴天", "晴天"},
		{"给我点首晴天", "晴天"},
		{"给我来一首晴天", "晴天"},
		{"发我一首晴天", "晴天"},
		{"我想听晴天", "晴天"},
		{"我想听周杰伦的歌", "周杰伦"},
		{"我想听周杰伦", "周杰伦"},
		{"我要听晴天", "晴天"},
		{"@肉丸 点歌 晴天", "晴天"},
		{"@肉丸叔叔\u2005来首稻香", "稻香"},
	}

	for _, tc := range tests {
		t.Run(tc.input, func(t *testing.T) {
			actual := extractSongName(tc.input)
			if actual != tc.expected {
				t.Errorf("extractSongName(%q) = %q, want %q", tc.input, actual, tc.expected)
			}
		})
	}
}
